/*
 * Generates the SQL seed files under db/ from kpi-catalog.json,
 * operand-registry.json and dataset.json. Run: node gen-sql.js
 */
const fs = require("fs");
const path = require("path");
const KPI_CATALOG = require("./kpi-catalog.json");
const OPERAND_REGISTRY = require("./operand-registry.json");
const dataset = require("./dataset.json");

const DB = path.join(__dirname, "..", "db");

function q(v) {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return isFinite(v) ? String(v) : "NULL";
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  return "'" + String(v).replace(/'/g, "''") + "'";
}
function jsonb(v) {
  return v === null || v === undefined ? "NULL" : q(JSON.stringify(v)) + "::jsonb";
}

// ---------------------------------------------------------------------
// 002_seed_kpi_catalog.sql
// ---------------------------------------------------------------------
let sql = "-- Seed: Advantedge Operations KPI catalog (" + KPI_CATALOG.length + " measures)\n";
sql += "-- Generated by engine/gen-sql.js from kpi-catalog.json (extracted from the Advantedge Operations HTML tool)\n\n";
sql += "TRUNCATE kpi_catalog CASCADE;\n\n";
KPI_CATALOG.forEach((e) => {
  const t = (e.benchmark && e.benchmark.threshold) || {};
  sql +=
    "INSERT INTO kpi_catalog (code, section, name, unit, source, intake, formula, benchmark_value, benchmark_source, benchmark_basis, " +
    "threshold_scored, threshold_direction, threshold_target, threshold_lo, threshold_hi, cms_fetched) VALUES (" +
    [
      q(e.code), q(e.section), q(e.name), q(e.unit), q(e.source), q(e.intake), q(e.formula),
      q(e.benchmark && e.benchmark.value), q(e.benchmark && e.benchmark.source), q(e.benchmark && e.benchmark.basis),
      t.scored === true ? "TRUE" : t.scored === false ? "FALSE" : "NULL",
      q(t.direction), q(t.target), q(t.lo), q(t.hi),
      e.cmsFetched ? "TRUE" : "FALSE",
    ].join(", ") + ");\n";
  (e.inputs || []).forEach((i) => {
    sql += "INSERT INTO kpi_inputs (kpi_code, input_key, label, unit) VALUES (" + [q(e.code), q(i.key), q(i.label), q(i.unit)].join(", ") + ");\n";
  });
});
fs.writeFileSync(path.join(DB, "002_seed_kpi_catalog.sql"), sql);

// ---------------------------------------------------------------------
// 003_seed_operand_registry.sql
// ---------------------------------------------------------------------
let sql2 = "-- Seed: operand registry (" + Object.keys(OPERAND_REGISTRY).length + " fields the onboarding tool can capture)\n\n";
sql2 += "TRUNCATE operand_registry CASCADE;\n\n";
Object.entries(OPERAND_REGISTRY).forEach(([k, o]) => {
  sql2 += "INSERT INTO operand_registry (operand_key, label, unit, family, intake) VALUES (" + [q(k), q(o.label), q(o.unit), q(o.family), q(o.intake)].join(", ") + ");\n";
});
fs.writeFileSync(path.join(DB, "003_seed_operand_registry.sql"), sql2);

// ---------------------------------------------------------------------
// 004_seed_demo_community.sql
// ---------------------------------------------------------------------
const p = dataset.profile;
let sql3 = "-- Seed: synthetic demo community (\"" + p.communityName + "\") — fabricated data for the POC demo\n\n";
sql3 += "INSERT INTO communities (slug, name, operator, address, city_state_zip, state_abbr, units_il, units_al, units_mc, units_snf, " +
  "sqft_il, sqft_al, sqft_mc, sqft_snf, sqft_total, current_occupancy, occupancy_il, occupancy_al, occupancy_mc, occupancy_snf, year_opened, care_levels, structure) VALUES (\n" +
  [
    q("cedar-bluff-commons"), q(p.communityName), q(p.operator), q(p.address), q(p.cityStateZip), q(p.stateAbbr),
    p.units.IL, p.units.AL, p.units.MC, p.units.SNF, p.sqft.IL, p.sqft.AL, p.sqft.MC, p.sqft.SNF, p.sqft.total, p.currentOccupancy,
    p.occupancyByLevel.IL, p.occupancyByLevel.AL, p.occupancyByLevel.MC, p.occupancyByLevel.SNF, p.yearOpened,
    "ARRAY[" + p.careLevels.map(q).join(",") + "]", jsonb(p.structure),
  ].join(", ") + "\n)\nON CONFLICT (slug) DO UPDATE SET\n  name = EXCLUDED.name, current_occupancy = EXCLUDED.current_occupancy," +
  " sqft_il = EXCLUDED.sqft_il, sqft_al = EXCLUDED.sqft_al, sqft_mc = EXCLUDED.sqft_mc, sqft_snf = EXCLUDED.sqft_snf, sqft_total = EXCLUDED.sqft_total," +
  " occupancy_il = EXCLUDED.occupancy_il, occupancy_al = EXCLUDED.occupancy_al, occupancy_mc = EXCLUDED.occupancy_mc, occupancy_snf = EXCLUDED.occupancy_snf\nRETURNING id;\n\n";

sql3 += "-- Operand values (editable — this is the data an operator would upload/update per report cycle)\n";
sql3 += "DELETE FROM operand_values WHERE community_id = (SELECT id FROM communities WHERE slug = 'cedar-bluff-commons');\n\n";
// A handful of keys (e.g. totalResidents) are shared across families/buckets in
// the source dataset; operand_values is one row per key, so dedupe, preferring
// the operand's registry-declared family as its canonical source bucket.
const seenKeys = new Set();
for (const [bucket, fam] of Object.entries(dataset.operands)) {
  for (const [k, v] of Object.entries(fam)) {
    if (seenKeys.has(k)) continue;
    seenKeys.add(k);
    const canonicalBucket = (OPERAND_REGISTRY[k] || {}).family || bucket;
    const isNum = typeof v === "number";
    sql3 +=
      "INSERT INTO operand_values (community_id, operand_key, value, text_value, source_bucket) VALUES (" +
      "(SELECT id FROM communities WHERE slug = 'cedar-bluff-commons'), " +
      [q(k), isNum ? v : "NULL", isNum ? "NULL" : q(v), q(canonicalBucket)].join(", ") +
      ");\n";
  }
}

sql3 += "\n-- CMS Five-Star mock fetch (simulates Care Compare; in production this is a live API pull, not an upload)\n";
sql3 += "DELETE FROM cms_fivestar_values WHERE community_id = (SELECT id FROM communities WHERE slug = 'cedar-bluff-commons');\n\n";
for (const [code, c] of Object.entries(dataset.cms)) {
  sql3 +=
    "INSERT INTO cms_fivestar_values (community_id, kpi_code, value_text, status, note) VALUES (" +
    "(SELECT id FROM communities WHERE slug = 'cedar-bluff-commons'), " +
    [q(code), q(c.value), q(c.status), q(c.note)].join(", ") +
    ");\n";
}
fs.writeFileSync(path.join(DB, "004_seed_demo_community.sql"), sql3);

console.log("Wrote 002_seed_kpi_catalog.sql, 003_seed_operand_registry.sql, 004_seed_demo_community.sql to db/");
